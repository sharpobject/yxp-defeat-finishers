#!/usr/bin/env python3
"""Emit the eleven verified finisher files as direct C# 7.3 byte-array factories.

Only this build-time tool reads filenames and checks hashes. The generated
runtime methods allocate one requested byte array and initialize it from the
compiler's RVA data. PNG/WAV bytes retain their original encoding. There is no
resource-name lookup, reflection, Base64 conversion or eager media allocation.
The source media and generated C# stay outside source-control publication.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
from pathlib import Path


# filename, direct runtime method, reviewed release-media SHA-256
ASSETS = (
    ("tu-raging-demon.wav", "TuRagingDemon", "da5db72985fdf3248fb917e885c335083776233ef54a5fd3a32b1812cfa120f0"),
    ("lin-roadroller.wav", "LinRoadroller", "5d2bc4b6e741f3e80df163d19568ff156ad880806780bfff38cecfcd5bf3176a"),
    ("steamroller.png", "Steamroller", "902e76c38038a082787d1307fe3aaa8a5a75e2703e1c94123c0d4e3d67dd669b"),
    ("duck-calligraphy.png", "DuckCalligraphy", "3a5a963434efe5973b68bc3ad517b1e0bb1aee5045ceecfe21294716f88a7f48"),
    ("tu-third-strike-flame.png", "TuFlame", "3e9dd301288d11c9e044d511a0fff038179bd7162e7967b21ded655dbcd76b68"),
    ("dio-knife.png", "DioKnife", "5a8932147b804ffbbeccc58aa1232788066d42be55ae82fdd9d20cc7751fecea"),
    ("dio-superflash.png", "DioSuperflash", "fb87cbbb0f4286361f01239121fda333019f6c380b55f882d8c858c625db22a1"),
    ("tu-third-strike-superflash.png", "TuSuperflash", "8fb112cbc9be19adb94744cbbb91e1b684e3ea7d34f671a4fbcc87637d01ed55"),
    ("tu-third-strike-hit-sparks.png", "TuHitSparks", "5e6de89731f51d289336b34a291f129eff957238bee5b227c9afe241c5ed4f73"),
    ("lin-portrait-strip.png", "LinPortrait", "60d4e766c77b62f34ce1c7c9b51421b85d613e0fea6b464d89c0f5a5b01ec0e1"),
    ("tu-portrait-strip.png", "TuPortrait", "6f674b248753fcee7533ccb032b68ed007c6264a04cb8f5b0dc3dbb1fbda13d1"),
)

PCM_SAMPLES = {"tu-raging-demon.wav": 149940, "lin-roadroller.wav": 244755}


def emit(assets: Path, output: Path) -> dict:
    blobs = []
    for filename, method, expected in ASSETS:
        data = (assets / filename).read_bytes()
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise ValueError("Finisher media differs from reviewed bytes: " + filename)
        if filename in PCM_SAMPLES:
            count = PCM_SAMPLES[filename]
            header = struct.unpack_from("<4sI4s4sIHHIIHH4sI", data)
            expected_header = (b"RIFF", len(data) - 8, b"WAVE", b"fmt ", 16,
                               1, 1, 22050, 44100, 2, 16, b"data", count * 2)
            if header != expected_header or len(data) != 44 + count * 2:
                raise ValueError("Prepared PCM declarations changed: " + filename)
        blobs.append((filename, method, actual, data))
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("// Generated by emit_media.py. Do not edit or publish game-derived media as authored source.\n")
        stream.write("namespace YxpDefeatFinishers\n{\n    internal static class FinisherMedia\n    {\n")
        for filename, method, digest, data in blobs:
            stream.write("        // " + filename + " SHA256 " + digest + "\n")
            stream.write("        internal static byte[] " + method + "()\n        {\n            return new byte[]\n            {\n")
            for offset in range(0, len(data), 24):
                stream.write("                " + ",".join("0x" + format(value, "02x") for value in data[offset:offset + 24]) + ",\n")
            stream.write("            };\n        }\n")
        stream.write("    }\n}\n")
    return {
        "namespace": "YxpDefeatFinishers",
        "class": "FinisherMedia",
        "source": str(output),
        "source_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "media_bytes": sum(len(item[3]) for item in blobs),
        "assets": [dict(name=name, method=method, sha256=digest, bytes=len(data))
                   for name, method, digest, data in blobs],
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--manifest", type=Path)
    args = parser.parse_args()
    report = emit(args.assets, args.output)
    text = json.dumps(report, indent=2) + "\n"
    if args.manifest:
        args.manifest.parent.mkdir(parents=True, exist_ok=True)
        args.manifest.write_text(text)
    print(text, end="")
