#!/usr/bin/env python3
"""Adapt the reviewed native-stage artwork to the SDK's frame/media APIs.

The visual geometry and costume tracks stay in their existing maintained
sources. Only the async playback owner and filesystem media reads change.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from emit_media import ASSETS


def replace_once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise ValueError("Visual source boundary changed: " + old[:100])
    return text.replace(old, new)


def prepare(source: Path, output: Path) -> dict:
    raw = source.read_text()
    text = raw
    start = text.index("    internal sealed class Playback\n")
    end = text.index("    private static bool Alive(", start)
    text = text[:start] + text[end:]
    text = text.replace("using Cysharp.Threading.Tasks;\n", "")
    text = text.replace("using UnityEngine.Networking;\n", "using YxpDefeatFinishers;\n")
    # Resolve every media call at preparation, so the runtime never selects a
    # resource by filename or rebuilds an asset dictionary.
    text = replace_once(text,
        'Texture(kind == 1 ? "tu-portrait-strip.png" : "lin-portrait-strip.png", false)',
        'Texture(kind == 1 ? FinisherMedia.TuPortrait() : FinisherMedia.LinPortrait(), false)')
    for filename, method, _ in ASSETS:
        if filename.endswith(".png") and "portrait-strip" not in filename:
            text = replace_once(text, 'Texture("' + filename + '",',
                                'Texture(FinisherMedia.' + method + '(),')
    text = replace_once(text, 'private Texture2D Texture(string name, bool pixelArt)',
                        'private Texture2D Texture(byte[] bytes, bool pixelArt)')
    text = replace_once(text,
        'File.ReadAllBytes(Path.Combine(Application.streamingAssetsPath,\n                "YxpFinishers", name))',
        'bytes')
    text = replace_once(text, '"Finisher artwork unavailable: " + name',
                        '"Finisher artwork unavailable."')
    start = text.index("        internal async UniTask LoadSound(")
    end = text.index("        internal void Demon(", start)
    text = text[:start] + '''        internal void LoadSound(int movieKind)
        {
            clip = movieKind == 1 ? FinisherMediaAudio.TuRagingDemon() : FinisherMediaAudio.LinRoadroller();
            sound.clip = clip;
        }
''' + text[end:]
    # These four effects are retained in tuBursts and never found by name.
    text = text.replace('"ThirdStrikeHit" + i,', '"ThirdStrikeHit",')
    if "async " in text or "File." in text or "Path." in text or "UniTask" in text:
        raise ValueError("Visual adaptation left a task or filesystem consumer.")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("// Generated by prepare_visuals.py from the reviewed native-stage visuals.\n" + text)
    return {"source_sha256": hashlib.sha256(raw.encode()).hexdigest(),
            "output_sha256": hashlib.sha256(output.read_bytes()).hexdigest()}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(prepare(args.source, args.output), indent=2))
